import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";
import { createDeterministicMarketDataService } from "@/features/market-data/deterministic/service";
import { EtfAnalytics } from "./etf-analytics";

describe("ETF analytics presentation", () => {
  it("renders sample overview, weights, concentration, exposures, and keyboard-reachable explanations", async () => {
    const snapshot = await createDeterministicMarketDataService().getEtfAnalytics("IE-XETR:VWCE");
    const html = renderToStaticMarkup(<EtfAnalytics snapshot={snapshot} message={null} />);
    expect(html).toContain("Přehled fondu");
    expect(html).toContain("0,22\u00a0%");
    expect(html).toContain("14,8B EUR");
    expect(html).toContain("NAV");
    expect(html).toContain("Největší pozice");
    expect(html).toContain("Sample Atlas Devices");
    expect(html).toContain("Podíl 10 největších pozic");
    expect(html).toContain("23,1\u00a0%");
    expect(html).toContain("12 · 3\u00a0600 celkem podle zdroje");
    expect(html).toContain("Sektorové zastoupení");
    expect(html).toContain("Geografické zastoupení");
    expect(html).toContain("aria-label=\"Více o položce Nákladovost\"");
    expect(html).toContain("Ukázková data");
    expect(html).not.toContain("P/E TTM");
    expect(html).not.toContain("Live holdings");
  });
  it("preserves successful sections when a dataset is unavailable and leaves no sample label in real mode", async () => {
    const sample = await createDeterministicMarketDataService().getEtfAnalytics("IE-XETR:VWCE");
    const partial = { ...sample, countries: null, unavailableDatasets: ["countries" as const], info: sample.info && { ...sample.info, isDeterministic: false }, holdings: sample.holdings && { ...sample.holdings, isDeterministic: false }, sectors: sample.sectors && { ...sample.sectors, isDeterministic: false } };
    const html = renderToStaticMarkup(<EtfAnalytics snapshot={partial} message={null} />);
    expect(html).toContain("Největší pozice");
    expect(html).toContain("Geografické zastoupení");
    expect(html).toContain("Data této části teď nejsou dostupná");
    expect(html).not.toContain("Sample data");
    const failed = renderToStaticMarkup(<EtfAnalytics snapshot={null} message="Fund composition is unavailable right now." />);
    expect(failed).toContain("Fund composition is unavailable right now.");
    expect(failed).toContain("Největší pozice");
  });
  it("renders dated metrics, aged regulatory holdings, coverage and escaped source attribution", async () => {
    const sample = await createDeterministicMarketDataService().getEtfAnalytics("IE-XETR:VWCE");
    const source = { name: "TickerInside", url: "https://tickerinside.com/etf/voo/", citation: '<script>alert("citation")</script>', license: "CC BY 4.0" };
    const holdings = { ...sample.holdings!, source, provider: "tickerinside", isDeterministic: false, sourceKind: "regulatory-filing" as const, asOf: "2026-06-30T00:00:00.000Z", retrievedAt: "2026-10-19T12:00:00.000Z" };
    const snapshot = { ...sample, holdings, info: { ...sample.info!, source, isDeterministic: false, value: { ...sample.info!.value, nav: null, holdingsCount: null, assetsScope: "etf-share-class" as const, expenseRatioAsOf: "2026-01-15T00:00:00.000Z", assetsAsOf: "2026-08-31T00:00:00.000Z" } }, sectors: { ...sample.sectors!, source, isDeterministic: false, completeness: "partial" as const, coverage: { knownWeight: 0.4, unclassifiedWeight: 0.6, inferred: true } } };
    const html = renderToStaticMarkup(<EtfAnalytics snapshot={snapshot} message={null} now={new Date("2026-10-19T12:00:00.000Z")} />);
    expect(html).toContain("Zdroj ETF dat:");
    expect(html).toContain('href="https://tickerinside.com/etf/voo/"');
    expect(html).toContain("CC BY 4.0");
    expect(html).toContain("&lt;script&gt;");
    expect(html).not.toContain("<script>");
    expect(html).toContain("Stav složení k 30. 6. 2026");
    expect(html).toContain("Složení je staré 111 dní");
    expect(html).toContain("Snímek z regulatorního hlášení");
    expect(html).toContain("Údaj k 15. 1. 2026");
    expect(html).toContain("Údaj k 31. 8. 2026");
    expect(html).toContain("AUM představuje čistá aktiva ETF třídy");
    expect(html).toContain("Zachycené zastoupení: 40");
    expect(html).toContain("Bez zařazení: 60");
    expect(html).toContain("Váhy nejsou přepočítané na 100 %");
    expect(html).toContain("Zařazení je odvozené");
    expect(html).toContain("Načteno 19. 10. 2026");
    const withoutInfo = renderToStaticMarkup(<EtfAnalytics snapshot={{ ...snapshot, info: null }} message={null} />);
    expect(withoutInfo).toContain("Zdroj ETF dat:");
    const unsafe = renderToStaticMarkup(<EtfAnalytics snapshot={{ ...snapshot, holdings: { ...snapshot.holdings, source: { ...source, url: "javascript:alert(1)" } } }} message={null} />);
    expect(unsafe).not.toContain("javascript:");
  });
});
